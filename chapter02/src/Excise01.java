public class Excise01 {
    public static void main(String[] a){
        float PI=3.14F;
        float r1=1.2F;
        float r2=2.5F;
        int   r3=6;
        System.out.println("第一个圆的面积"+PI*r1*r1);
        System.out.println("第二个圆的面积"+PI*r2*r2);
        System.out.println("第三个圆的面积"+PI*r3*r3);
    }
    
}
